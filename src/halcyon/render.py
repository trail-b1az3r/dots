# ── Lua helpers ────────────────────────────────────────────────────────


def lua_string(value: str) -> str:
    """Quote a Lua string literal safely.

    Generated files contain user-supplied text (font names, commands,
    workspace names), so this has to be correct rather than convenient.
    """
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def lua_value(value: Any, indent: int = 0) -> str:
    pad = "    " * indent
    inner = "    " * (indent + 1)
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nil"
    if isinstance(value, (int, float)):
        if isinstance(value, float) and value == int(value):
            return str(int(value))
        return repr(value)
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, (list, tuple)):
        if not value:
            return "{}"
        items = ",\n".join(f"{inner}{lua_value(item, indent + 1)}" for item in value)
        return "{\n" + items + f",\n{pad}}}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = []
        for key, item in value.items():
            key_text = (
                str(key)
                if str(key).isidentifier()
                else f"[{lua_string(str(key))}]"
            )
            lines.append(f"{inner}{key_text} = {lua_value(item, indent + 1)}")
        return "{\n" + ",\n".join(lines) + f",\n{pad}}}"
    raise TypeError(f"Cannot express {type(value).__name__} in Lua")


def _lua_banner() -> str:
    return "".join(f"-- {line}\n" for line in BANNER.splitlines())


def write_atomic(path: os.PathLike[str] | str, content: str) -> None:
    path = str(path)
    directory = os.path.dirname(path) or "."
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".halcyon-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


