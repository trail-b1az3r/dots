def _argb_to_hypr(value: str) -> str:
    """`#AARRGGBB` → Hyprland's `rgba(RRGGBBAA)` string form."""
    raw = value.lstrip("#")
    if len(raw) == 8:
        return f"rgba({raw[2:]}{raw[0:2]})"
    if len(raw) == 6:
        return f"rgba({raw}ff)"
    return value


# ── Hyprland: animations ───────────────────────────────────────────────


def render_hypr_animations_lua(tokens: dict[str, Any]) -> str:
    motion = tokens["motion"]
    preset = motion["preset"]
    table = dict(_MACOS)
    table.update(_preset_overrides(preset))

    out: list[str] = [_lua_banner(), ""]
    out.append("local hl = hl\n")
    out.append("-- Shared easing curves. QML uses the same control points so an\n")
    out.append("-- overlay fading in over a window matches the window's own motion.\n")
    for key, control in motion["curve"].items():
        name = CURVE_NAMES.get(key)
        if not name:
            continue
        x1, y1, x2, y2 = control
        out.append(
            f'hl.curve({lua_string(name)}, {{ type = "bezier", '
            f"points = {{ {{{x1}, {y1}}}, {{{x2}, {y2}}} }} }})\n"
        )

    if motion["springs"]:
        out.append("\n-- Springs carry the weight of window motion; stiffness sets the\n")
        out.append("-- speed and dampening removes the bounce.\n")
        out.append(
            f'hl.curve({lua_string(_SPRING)}, {{ type = "spring", '
            "mass = 1, stiffness = 244, dampening = 25.5 })\n"
        )
        out.append(
            f'hl.curve({lua_string(_SOFT)}, {{ type = "spring", '
            "mass = 1, stiffness = 168, dampening = 24 })\n"
        )

    out.append("\nhl.config({ animations = { enabled = ")
    out.append("false" if motion["disabled"] else "true")
    out.append(", workspace_wraparound = false } })\n\n")

    if motion["disabled"]:
        out.append("-- Animations are switched off; nothing further to declare.\n")
        return "".join(out)

    durations = motion["duration"]
    for leaf, spec in table.items():
        duration_key, curve_key, style, use_spring = spec
        if duration_key is None:
            # Continuously-animating leaves (gradient angles) stay off:
            # they redraw every frame forever and cost real battery.
            out.append(
                f'hl.animation({{ leaf = {lua_string(leaf)}, enabled = false }})\n'
            )
            continue

        ms = durations.get(duration_key, durations["standard"])
        speed = max(0.1, round(ms / 100.0, 2))
        parts = [f"leaf = {lua_string(leaf)}", "enabled = true", f"speed = {speed}"]
        if use_spring and motion["springs"]:
            parts.append(f"spring = {lua_string(_SPRING)}")
        else:
            parts.append(f"bezier = {lua_string(CURVE_NAMES[curve_key])}")
        if style:
            parts.append(f"style = {lua_string(style)}")
        out.append("hl.animation({ " + ", ".join(parts) + " })\n")

    return "".join(out)


# ── Hyprland: keybinds ─────────────────────────────────────────────────


class KeybindError(ValueError):
    """A catalog entry that cannot be turned into a safe binding."""


def halcyon_binary() -> str:
    """The `halcyon` launcher, as an absolute path where we can find one.

    Hyprland runs `exec_cmd` through /bin/sh, which inherits the session's
    PATH — and ~/.local/bin is missing from it often enough that baking the
    resolved path into the generated file is the difference between binds
    that work and binds that silently do nothing. The file is regenerated
    on every `theme apply`, so nothing goes stale.
    """
    found = shutil.which("halcyon")
    if found:
        return found
    local = os.path.expanduser("~/.local/bin/halcyon")
    if os.path.isfile(local) and os.access(local, os.X_OK):
        return local
    return "halcyon"


def render_hypr_keybinds_lua(
    settings: dict[str, Any], catalog: dict[str, Any]
) -> str:
    overrides = settings.get("keybinds") or {}
    binary = halcyon_binary()
    workspaces = settings.get("workspaces", {})
    count = max(1, min(20, int(workspaces.get("count", 10))))

    out: list[str] = [_lua_banner(), "\nlocal hl = hl\n\n"]
    out.append("-- Bindings come from settings.json layered over the shipped\n")
    out.append("-- catalog, so the Settings app can rebind anything without a\n")
    out.append("-- human editing Lua.\n\n")

    seen: dict[str, str] = {}
    for entry in catalog.get("binds", []):
        bind_id = entry["id"]
        binding = str(overrides.get(bind_id, entry.get("default", ""))).strip()
        if not binding or binding.lower() in ("none", "unbound", "disabled"):
            continue

        normalised = binding.upper().replace(" ", "")
        if normalised in seen:
            out.append(
                f"-- skipped {bind_id}: {binding} is already bound to "
                f"{seen[normalised]}\n"
            )
            continue
        seen[normalised] = bind_id

        action = _bind_action(entry, binary)
        options = _bind_options(entry)
        suffix = f", {options}" if options else ""
        out.append(f"hl.bind({lua_string(binding)}, {action}{suffix})\n")

    # Workspace binds are generated here rather than as a Lua loop so they
    # go through the same duplicate check as everything else — which is
    # how the collision with the macOS capture shortcuts was found.
    #
    # Super+Shift+<n> is the usual Linux "move window to workspace", but
    # Super+Shift+3/4/5 are the macOS screenshot shortcuts this desktop
    # deliberately keeps. Rather than splitting the digits across two
    # modifiers, every move-to-workspace bind uses Super+Ctrl.
    out.append("\n-- Workspaces. Super switches, Super+Ctrl moves the window.\n")
    out.append("-- Super+Shift+<digit> is left to the macOS capture shortcuts.\n")
    for index in range(1, min(count, 10) + 1):
        key = index % 10
        for modifier, expression, label in (
            ("SUPER", f"hl.dsp.focus({{ workspace = {index} }})", f"Workspace {index}"),
            (
                "SUPER + CTRL",
                f"hl.dsp.window.move({{ workspace = {index}, follow = true }})",
                f"Move window to workspace {index}",
            ),
        ):
            binding = f"{modifier} + {key}"
            normalised = binding.upper().replace(" ", "")
            if normalised in seen:
                out.append(
                    f"-- skipped {label}: {binding} is already bound to "
                    f"{seen[normalised]}\n"
                )
                continue
            seen[normalised] = label
            out.append(
                f"hl.bind({lua_string(binding)}, {expression}, "
                f"{{ description = {lua_string(label)} }})\n"
            )
    out.append("\n")

    for entry in catalog.get("mouseBinds", []):
        binding = str(overrides.get(entry["id"], entry.get("default", ""))).strip()
        if not binding:
            continue
        action = _bind_action(entry, binary)
        out.append(f"hl.bind({lua_string(binding)}, {action}, {{ mouse = true }})\n")

    out.append(
        '\nhl.bind("SUPER + SHIFT + mouse_down", hl.dsp.focus({ workspace = "e+1" }))\n'
    )
    out.append(
        'hl.bind("SUPER + SHIFT + mouse_up", hl.dsp.focus({ workspace = "e-1" }))\n'
    )
    return "".join(out)


def _bind_action(entry: dict[str, Any], binary: str = "halcyon") -> str:
    run = entry.get("run") or {}
    if "exec" in run:
        command = str(run["exec"])
        if command == "halcyon" or command.startswith("halcyon "):
            command = binary + command[len("halcyon"):]
        return f"hl.dsp.exec_cmd({lua_string(command)})"
    if "dsp" in run:
        expression = str(run["dsp"]).strip()
        # The catalog is shipped data, but it is still data: only allow
        # it to name a dispatcher, never arbitrary Lua.
        if not expression.startswith("hl.dsp."):
            raise KeybindError(
                f"{entry.get('id')}: dispatcher must start with 'hl.dsp.', "
                f"got {expression!r}"
            )
        return expression
    raise KeybindError(f"{entry.get('id')}: no 'exec' or 'dsp' action")


_BIND_FLAGS = ("repeating", "locked", "release", "non_consuming", "long_press", "mouse")


def _bind_options(entry: dict[str, Any]) -> str:
    flags = entry.get("flags") or {}
    parts = [
        f"{name} = {'true' if flags[name] else 'false'}"
        for name in _BIND_FLAGS
        if name in flags
    ]
    title = entry.get("title")
    if title:
        parts.append(f"description = {lua_string(str(title))}")
    return "{ " + ", ".join(parts) + " }" if parts else ""


# ── Hyprland: runtime (input, monitors, rules, workspaces) ─────────────


def render_hypr_runtime_lua(
    settings: dict[str, Any], tokens: dict[str, Any], environment: dict[str, str]
) -> str:
    inp = settings.get("input", {})
    displays = settings.get("displays", {})
    workspaces = settings.get("workspaces", {})
    power = settings.get("power", {})
    graphics = settings.get("graphics", {})

    out: list[str] = [_lua_banner(), "\nlocal hl = hl\n\n"]

    out.append("-- Environment. Detected at install time from the hardware that\n")
    out.append("-- is actually present, never applied blindly.\n")
    for key, value in environment.items():
        out.append(f"hl.env({lua_string(key)}, {lua_string(str(value))})\n")

    out.append("\nhl.config(")
    config = {
        "input": {
            "kb_layout": str(inp.get("keyboardLayout", "us")),
            "kb_variant": str(inp.get("keyboardVariant", "")),
            "kb_options": str(inp.get("keyboardOptions", "")),
            "repeat_rate": int(inp.get("repeatRate", 35)),
            "repeat_delay": int(inp.get("repeatDelay", 280)),
            "follow_mouse": int(inp.get("followMouse", 1)),
            "sensitivity": float(inp.get("sensitivity", 0.0)),
            "accel_profile": str(inp.get("accelProfile", "adaptive")),
            "natural_scroll": bool(inp.get("naturalScroll", True)),
            "scroll_factor": float(inp.get("scrollFactor", 1.0)),
            "touchpad": {
                "natural_scroll": bool(inp.get("touchpadNaturalScroll", True)),
                "tap_to_click": bool(inp.get("tapToClick", True)),
                "disable_while_typing": bool(inp.get("disableWhileTyping", True)),
                "tap_and_drag": True,
                "drag_lock": True,
            },
        },
        "general": {
            "allow_tearing": bool(displays.get("allowTearing", False)),
        },
        "misc": {
            "vrr": int(displays.get("vrr", 1)),
            "render_unfocused_fps": int(graphics.get("renderUnfocusedFps", 10)),
            "focus_on_activate": True,
            "animate_manual_resizes": not tokens["motion"]["disabled"],
            "animate_mouse_windowdragging": False,
            "disable_hyprland_logo": True,
            "disable_splash_rendering": True,
            "force_default_wallpaper": 0,
            "background_color": _argb_to_hypr(tokens["color"]["backdrop"]),
        },
        "cursor": {
            "inactive_timeout": 5,
            "hide_on_key_press": False,
            "no_hardware_cursors": 2,
            "warp_on_change_workspace": 2,
        },
        "binds": {
            "workspace_back_and_forth": True,
            "allow_workspace_cycles": True,
            "movefocus_cycles_fullscreen": False,
            "hide_special_on_workspace_change": True,
        },
        "dwindle": {
            "preserve_split": True,
            "smart_split": False,
            "smart_resizing": True,
            "default_split_ratio": 1.0,
        },
        "master": {"new_status": "master", "mfact": 0.55},
    }
    # Refuse to emit an option Hyprland does not have, or a number outside
    # its documented range: a config error here costs the user a broken
    # session, and we can see it coming.
    problems = hyprland.validate_options(config)
    if problems:
        raise RenderError(
            "Generated Hyprland config would be invalid:\n  - "
            + "\n  - ".join(problems)
        )

    out.append(lua_value(config))
    out.append(")\n\n")

    swipe_fingers = int(inp.get("swipeFingers", 3))
    if inp.get("workspaceSwipe", True):
        out.append("-- Three-finger swipe moves between workspaces, matching the\n")
        out.append("-- gesture people arrive from macOS expecting.\n")
        out.append(
            "hl.gesture({ fingers = "
            f"{swipe_fingers}, direction = \"horizontal\", action = \"workspace\" }})\n\n"
        )

    monitors = displays.get("monitors") or []
    if monitors:
        out.append("-- Configured displays.\n")
        for monitor in monitors:
            spec = {
                "output": str(monitor.get("output", "")),
                "mode": str(monitor.get("mode", "preferred")),
                "position": str(monitor.get("position", "auto")),
                "scale": monitor.get("scale", "auto"),
            }
            for optional in ("transform", "vrr", "bitdepth", "mirror", "disabled"):
                if optional in monitor:
                    spec[optional] = monitor[optional]
            out.append(f"hl.monitor({lua_value(spec)})\n")
    else:
        out.append("-- No displays configured: accept whatever is plugged in.\n")
        out.append(
            'hl.monitor({ output = "", mode = "preferred", position = "auto", '
            f'scale = {lua_string(str(displays.get("defaultScale", "auto")))} }})\n'
        )
    out.append("\n")

    out.append(_workspace_rules(workspaces))
    out.append(_window_rules(tokens, power))
    out.append(_layer_rules(tokens))
    return "".join(out)


def _workspace_rules(workspaces: dict[str, Any]) -> str:
    count = max(1, min(20, int(workspaces.get("count", 10))))
    names = workspaces.get("names") or {}
    persistent = bool(workspaces.get("persistent", True))
    smart_gaps = bool(workspaces.get("smartGaps", True))

    out = ["-- Workspaces behave like macOS Spaces: they exist before you\n"]
    out.append("-- visit them, and they keep their name and monitor.\n")
    for index in range(1, count + 1):
        rule: dict[str, Any] = {
            "workspace": str(index),
            "persistent": persistent,
        }
        label = names.get(str(index)) or names.get(index)
        if label:
            rule["default_name"] = str(label)
        if index == 1:
            rule["default"] = True
        out.append(f"hl.workspace_rule({lua_value(rule)})\n")

    if smart_gaps:
        out.append("\n-- No gaps or rounding when a workspace holds a single tiled\n")
        out.append("-- window, so a maximised editor fills the screen cleanly.\n")
        out.append('hl.workspace_rule({ workspace = "w[tv1]", gaps_out = 0, gaps_in = 0 })\n')
        out.append('hl.workspace_rule({ workspace = "f[1]", gaps_out = 0, gaps_in = 0 })\n')
        out.append(
            'hl.window_rule({ name = "halcyon-solo-tiled", '
            'match = { float = false, workspace = "w[tv1]" }, '
            "border_size = 0, rounding = 0 })\n"
        )
        out.append(
            'hl.window_rule({ name = "halcyon-solo-fullscreen", '
            'match = { float = false, workspace = "f[1]" }, '
            "border_size = 0, rounding = 0 })\n"
        )
    out.append("\n")
    return "".join(out)


