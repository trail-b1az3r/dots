def _layer_rules(tokens: dict[str, Any]) -> str:
    """Blur behind the shell's own layers — this is what makes the glass.

    `ignore_alpha` stops the fully transparent parts of an overlay from
    being blurred, which is both a correctness fix (no halo around a
    floating panel) and a large saving on fill rate.
    """
    blur_enabled = bool(tokens["blur"]["enabled"])
    namespaces = [
        ("halcyon-bar", 0.16),
        ("halcyon-overlay", 0.1),
        ("halcyon-spotlight", 0.06),
        ("halcyon-control", 0.1),
        ("halcyon-assistant", 0.06),
        ("halcyon-notifications", 0.14),
        ("halcyon-osd", 0.14),
        ("halcyon-overview", 0.04),
        ("halcyon-switcher", 0.08),
        ("halcyon-dashboard", 0.1),
        ("waybar", 0.16),
    ]

    out = ["-- Layer rules: the shell's surfaces are what get the real blur.\n"]
    for namespace, ignore_alpha in namespaces:
        rule: dict[str, Any] = {
            "name": f"halcyon-layer-{namespace}",
            "match": {"namespace": f"^{namespace}$"},
            "blur": blur_enabled,
            "xray": bool(tokens["blur"]["xray"]),
        }
        if blur_enabled:
            rule["ignore_alpha"] = ignore_alpha
        out.append(f"hl.layer_rule({lua_value(rule)})\n")

    out.append(
        'hl.layer_rule({ name = "halcyon-layer-lock", '
        'match = { namespace = "^halcyon-lock$" }, above_lock = 1, no_screen_share = true })\n'
    )
    out.append("\n")
    return "".join(out)


# ── Waybar configuration ───────────────────────────────────────────────


def render_waybar_config(
    settings: dict[str, Any], tokens: dict[str, Any], base: dict[str, Any]
) -> str:
    """Merge the shipped Waybar module definitions with the user's layout."""
    bar = settings.get("bar", {})
    power_refresh = settings.get("power", {}).get("refreshIntervals", {})
    interval = int(power_refresh.get("acSeconds", 5))

    config = dict(base)
    config["layer"] = "top"
    config["position"] = bar.get("position", "top")
    config["height"] = int(bar.get("height", 34))
    config["spacing"] = tokens["spacing"]["xs"]
    config["margin-top"] = int(bar.get("topMargin", 6)) if bar.get("floating", True) else 0
    config["margin-left"] = int(bar.get("sideMargin", 10)) if bar.get("floating", True) else 0
    config["margin-right"] = config["margin-left"]
    config["modules-left"] = list(bar.get("left", []))
    config["modules-center"] = list(bar.get("center", []))
    config["modules-right"] = list(bar.get("right", []))
    if not bar.get("showOnAllMonitors", True):
        config["output"] = ["!*"]

    # Polling intervals follow the power settings so a laptop on battery
    # is not woken five times a second to redraw a CPU percentage.
    for module in ("cpu", "memory", "temperature", "disk"):
        if module in config and isinstance(config[module], dict):
            config[module]["interval"] = max(1, interval)
    if "custom/gpu" in config:
        config["custom/gpu"]["interval"] = max(2, interval * 2)
    if "custom/hypernix" in config:
        config["custom/hypernix"]["interval"] = max(
            10, int(settings.get("hypernix", {}).get("pollSeconds", 60))
        )

    if not settings.get("hypernix", {}).get("enabled", True):
        for key in ("modules-left", "modules-center", "modules-right"):
            config[key] = [m for m in config[key] if m != "custom/hypernix"]
    if not settings.get("assistant", {}).get("enabled", True):
        for key in ("modules-left", "modules-center", "modules-right"):
            config[key] = [m for m in config[key] if m != "custom/assistant"]

    used = set(config["modules-left"] + config["modules-center"] + config["modules-right"])
    for key in list(config):
        if ("/" in key or key in _WAYBAR_BUILTIN) and key not in used:
            # Waybar instantiates every module it finds a definition for,
            # so leaving unused ones in place costs real CPU.
            del config[key]

    _resolve_waybar_commands(config, halcyon_binary())

    header = "\n".join(f"// {line}" for line in BANNER.splitlines())
    return header + "\n" + json.dumps(config, indent=2) + "\n"


#: Module fields Waybar executes as shell commands.
_WAYBAR_COMMAND_FIELDS = (
    "exec",
    "exec-if",
    "on-click",
    "on-click-middle",
    "on-click-right",
    "on-click-backward",
    "on-click-forward",
    "on-scroll-up",
    "on-scroll-down",
    "on-update",
    "on-double-click",
)


def _resolve_waybar_commands(config: dict[str, Any], binary: str) -> None:
    """Point every `halcyon ...` command at the binary by absolute path.

    Waybar runs these through /bin/sh with whatever PATH its unit
    inherited, and a systemd user session frequently does not have
    ~/.local/bin on it. A bare `halcyon` then fails silently — the button
    is there, it just does nothing, which is exactly how it was reported.
    The keybind renderer already resolves the path for the same reason;
    this is the other half of it.
    """
    if binary == "halcyon":
        # Nothing better was found, so leave the commands alone rather
        # than baking in a path that does not exist.
        return

    def rewrite(command: str) -> str:
        if command == "halcyon":
            return binary
        if command.startswith("halcyon "):
            return binary + command[len("halcyon"):]
        return command

    for key, module in config.items():
        if not isinstance(module, dict):
            continue
        for field in _WAYBAR_COMMAND_FIELDS:
            value = module.get(field)
            if isinstance(value, str):
                module[field] = rewrite(value)
        # `menu-actions` maps a menu entry to a command.
        actions = module.get("menu-actions")
        if isinstance(actions, dict):
            module["menu-actions"] = {
                name: rewrite(cmd) if isinstance(cmd, str) else cmd
                for name, cmd in actions.items()
            }


_WAYBAR_BUILTIN = {
    "battery", "backlight", "bluetooth", "clock", "cpu", "disk", "idle_inhibitor",
    "memory", "mpris", "network", "privacy", "pulseaudio", "temperature", "tray",
    "power-profiles-daemon", "keyboard-state", "user", "load",
}


# ── hyprlock and hypridle ──────────────────────────────────────────────
#
# Both are separate programs from the compositor and still use hyprlang,
# so they get their own small generated includes rather than Lua.


def render_hyprlock_colors(tokens: dict[str, Any]) -> str:
    colors = tokens["color"]
    typography = tokens["typography"]

    def hyprlang(name: str) -> str:
        raw = colors[name].lstrip("#")
        if len(raw) == 8:
            return f"rgba({raw[2:]}{raw[0:2]})"
        return f"rgba({raw}ff)"

    def bare(name: str) -> str:
        """The six-digit form, for Pango markup inside hyprlock labels."""
        return colors[name].lstrip("#")[2:]

    lines = [f"# {line}" for line in BANNER.splitlines()]
    lines.append("")
    for variable, token in (
        ("hal_text", "text"),
        ("hal_text_secondary", "textSecondary"),
        ("hal_text_tertiary", "textTertiary"),
        ("hal_surface", "surface"),
        ("hal_surface_raised", "surfaceRaised"),
        ("hal_border", "glassBorderStrong"),
        ("hal_accent", "accent"),
        ("hal_danger", "danger"),
        ("hal_warning", "warning"),
        ("hal_shadow", "shadow"),
    ):
        lines.append(f"${variable} = {hyprlang(token)}")

    for variable, token in (
        ("hal_text_rgb", "text"),
        ("hal_text_tertiary_rgb", "textTertiary"),
        ("hal_danger_rgb", "danger"),
        ("hal_accent_rgb", "accent"),
    ):
        lines.append(f"${variable} = {bare(token)}")

    lines.append(f"$hal_font_ui = {typography['family']}")
    lines.append(f"$hal_font_mono = {typography['mono']}")
    lines.append("")
    return "\n".join(lines)


def render_hypridle_timeouts(settings: dict[str, Any]) -> str:
    """Idle timeouts for the current power source.

    hypridle has no notion of "different timeouts on battery", so the
    active set is written here and rewritten by `halcyon power watch`
    when the machine is plugged in or unplugged.
    """
    from . import power as power_module

    idle = settings.get("power", {}).get("idle", {})
    battery = power_module.battery_state()
    on_battery = battery.present and not battery.plugged
    prefix = "battery" if on_battery else "ac"

    def seconds(name: str, fallback: int) -> int:
        return int(idle.get(f"{prefix}{name}", fallback))

    lines = [f"# {line}" for line in BANNER.splitlines()]
    lines.append(f"# Active set: {'on battery' if on_battery else 'on AC power'}.")
    lines.append("")

    if not idle.get("enabled", True):
        lines.append("# Idle handling is switched off in Settings → Battery.")
        lines.append("")
        return "\n".join(lines)

    steps = [
        (seconds("DimSeconds", 600), "halcyon backlight 15", "halcyon backlight 100"),
        (
            seconds("ScreenOffSeconds", 900),
            "hyprctl dispatch 'hl.dsp.dpms(\"off\")'",
            "hyprctl dispatch 'hl.dsp.dpms(\"on\")'",
        ),
        (seconds("LockSeconds", 1200), "loginctl lock-session", ""),
        (seconds("SuspendSeconds", 0), "systemctl suspend", ""),
    ]

    for timeout, on_timeout, on_resume in steps:
        if timeout <= 0:
            continue
        lines.append("listener {")
        lines.append(f"    timeout = {timeout}")
        lines.append(f"    on-timeout = {on_timeout}")
        if on_resume:
            lines.append(f"    on-resume = {on_resume}")
        lines.append("}")
        lines.append("")

    return "\n".join(lines)


# ── Orchestration ──────────────────────────────────────────────────────


def write_all(
    tokens: dict[str, Any],
    settings: dict[str, Any],
    catalog: dict[str, Any],
    waybar_base: dict[str, Any],
    environment: dict[str, str],
    *,
    outputs: Iterable[str] | None = None,
) -> list[str]:
    """Write every generated artefact; returns the paths written."""
    wanted = set(outputs) if outputs else None
    written: list[str] = []

    def emit(name: str, path: os.PathLike[str] | str, content: str) -> None:
        if wanted is not None and name not in wanted:
            return
        write_atomic(path, content)
        written.append(str(path))

    emit("theme", paths.THEME_JSON, render_theme_json(tokens))
    emit("waybar-css", paths.WAYBAR_CSS, render_waybar_css(tokens))
    emit("hypr-theme", paths.HYPR_THEME_LUA, render_hypr_theme_lua(tokens, settings))
    emit("hypr-animations", paths.HYPR_ANIM_LUA, render_hypr_animations_lua(tokens))
    emit(
        "hypr-keybinds",
        paths.GENERATED_DIR / "hypr-keybinds.lua",
        render_hypr_keybinds_lua(settings, catalog),
    )
    emit(
        "hypr-runtime",
        paths.GENERATED_DIR / "hypr-runtime.lua",
        render_hypr_runtime_lua(settings, tokens, environment),
    )
    emit(
        "waybar-config",
        paths.GENERATED_DIR / "waybar-config.jsonc",
        render_waybar_config(settings, tokens, waybar_base),
    )
    emit(
        "hyprlock",
        paths.GENERATED_DIR / "hyprlock-colors.conf",
        render_hyprlock_colors(tokens),
    )
    emit(
        "hypridle",
        paths.GENERATED_DIR / "hypridle-timeouts.conf",
        render_hypridle_timeouts(settings),
    )
    return written
