# ── Waybar colours (GTK3 CSS) ──────────────────────────────────────────

#: Waybar runs on GTK3, whose CSS has no custom properties — but it does
#: support `@define-color`, which is what we generate.
_WAYBAR_COLOR_KEYS = [
    "accent", "accentText", "accentHover", "accentPressed", "onAccent",
    "secondary", "tertiary",
    "text", "textSecondary", "textTertiary", "textDisabled",
    "surface", "surfaceRaised", "surfaceSunken", "surfaceHover",
    "surfacePressed", "surfaceSelected", "surfaceSolid",
    "glassTint", "glassHighlight", "glassBorder", "glassBorderStrong",
    "separator", "shadow", "scrim", "backdrop",
    "workspaceActive", "workspaceOccupied", "workspaceIdle",
    "success", "warning", "danger", "info",
]


def _argb_to_css(value: str) -> str:
    """`#AARRGGBB` → `rgba(r, g, b, a)`, which GTK3 understands."""
    raw = value.lstrip("#")
    if len(raw) == 8:
        a, r, g, b = (int(raw[i:i + 2], 16) for i in (0, 2, 4, 6))
    elif len(raw) == 6:
        a = 255
        r, g, b = (int(raw[i:i + 2], 16) for i in (0, 2, 4))
    else:
        return value
    return f"rgba({r}, {g}, {b}, {a / 255:.3f})"


def render_waybar_css(tokens: dict[str, Any]) -> str:
    colors = tokens["color"]
    typography = tokens["typography"]
    bar = tokens["bar"]
    radius = tokens["radius"]
    spacing = tokens["spacing"]
    motion = tokens["motion"]

    lines = [f"/* {line} */" for line in BANNER.splitlines()]
    lines.append("")
    for key in _WAYBAR_COLOR_KEYS:
        if key in colors:
            lines.append(f"@define-color hal-{_kebab(key)} {_argb_to_css(colors[key])};")

    # GTK3 has no variables beyond colours, so numeric tokens are emitted
    # as a small set of utility rules the static stylesheet composes with.
    lines += [
        "",
        "/* Metrics — GTK3 CSS has no custom properties, so the numbers the",
        "   theme controls land here as concrete rules. */",
        "",
        "window#waybar {",
        f"  font-family: \"{typography['family']}\", sans-serif;",
        f"  font-size: {typography['size']['body']}px;",
        "}",
        "",
        ".hal-pill {",
        f"  border-radius: {radius['md']}px;",
        f"  padding: 0 {spacing['sm']}px;",
        f"  margin: {max(2, bar['topMargin'] // 2)}px {spacing['xxs']}px;",
        "}",
        "",
        ".hal-group {",
        f"  border-radius: {radius['lg']}px;",
        f"  padding: 0 {spacing['xs']}px;",
        "}",
        "",
        ".hal-transition {",
        f"  transition: background-color {motion['duration']['quick']}ms ease,",
        f"              color {motion['duration']['quick']}ms ease;",
        "}",
        "",
    ]
    return "\n".join(lines) + "\n"


def _kebab(name: str) -> str:
    out: list[str] = []
    for index, char in enumerate(name):
        if char.isupper() and index:
            out.append("-")
        out.append(char.lower())
    return "".join(out)


